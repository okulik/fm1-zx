//! `fmzx-pack menu-art <png> -o <c file>`: the menu art's top band (240 x 64, `app/art/menu-top.png`)
//! as the run-length data `app/ui.c` decodes (`ui_art_top_row`).
//!
//! Each PNG colour maps by exact RGB to a UI palette index (`BAND`); any other colour is refused.
//! A row is a list of runs, one byte each: the band colour's position in `BAND` in the high
//! nibble, the run length minus one in the low nibble (1-16 pixels). A row's runs add up to 240.

use std::fmt::Write;

pub const W: usize = 240;
pub const H: usize = 64;

/// The band's colours: PNG RGB and the UI palette index it becomes (`ui_palette` in `app/ui.c`).
pub const BAND: [([u8; 3], u8); 11] = [
    ([0x00, 0x00, 0x00], 0),
    ([0xff, 0xff, 0xff], 15),
    ([0xcc, 0x99, 0xdd], 16),
    ([0x88, 0x77, 0xdd], 17),
    ([0x66, 0x66, 0xbb], 18),
    ([0x22, 0x11, 0x66], 19),
    ([0x33, 0x33, 0x66], 20),
    ([0x99, 0x88, 0xdd], 21),
    ([0x88, 0x77, 0xcc], 22),
    ([0x77, 0x66, 0xbb], 23),
    ([0xdd, 0xee, 0xee], 24),
];

/// The band's pixels as positions in `BAND`, row by row.
fn decode(png: &[u8]) -> Result<Vec<u8>, String> {
    let mut dec = png::Decoder::new(std::io::Cursor::new(png));
    dec.set_transformations(png::Transformations::EXPAND | png::Transformations::STRIP_16);
    let mut reader = dec.read_info().map_err(|e| format!("png: {e}"))?;
    let mut buf = vec![0; reader.output_buffer_size().ok_or("png: too large")?];
    let info = reader.next_frame(&mut buf).map_err(|e| format!("png: {e}"))?;
    if (info.width as usize, info.height as usize) != (W, H) {
        return Err(format!("the band must be {W}x{H}, the png is {}x{}", info.width, info.height));
    }
    let ch = info.color_type.samples();
    if ch < 3 {
        return Err("the png must be colour (indexed or RGB)".into());
    }
    let mut out = Vec::with_capacity(W * H);
    for (i, px) in buf.chunks(ch).take(W * H).enumerate() {
        let rgb = [px[0], px[1], px[2]];
        let k = BAND.iter().position(|(c, _)| *c == rgb).ok_or_else(|| {
            format!("pixel ({}, {}) is #{:02x}{:02x}{:02x}, not one of the band's colours", i % W, i / W, rgb[0], rgb[1], rgb[2])
        })?;
        out.push(k as u8);
    }
    Ok(out)
}

/// The C source of the band's data.
pub fn generate(png: &[u8]) -> Result<String, String> {
    let px = decode(png)?;
    let mut data: Vec<u8> = Vec::new();
    let mut offs: Vec<usize> = Vec::new();
    for row in px.chunks(W) {
        offs.push(data.len());
        let mut x = 0;
        while x < W {
            let mut n = 1;
            while x + n < W && n < 16 && row[x + n] == row[x] {
                n += 1;
            }
            data.push((row[x] << 4) | (n as u8 - 1));
            x += n;
        }
    }
    if data.len() > u16::MAX as usize {
        return Err("the band's data is too large".into());
    }
    let mut s = String::new();
    let w = &mut s;
    let e = |r: std::fmt::Result| r.map_err(|e| e.to_string());
    e(writeln!(w, "/* SPDX-FileCopyrightText: 2026 FM-1 ZX contributors */"))?;
    e(writeln!(w, "/* SPDX-License-Identifier: GPL-3.0-or-later */"))?;
    e(writeln!(w))?;
    e(writeln!(w, "/* Generated by `fmzx-pack menu-art app/art/menu-top.png -o app/menu_art.c`. Do not edit. */"))?;
    e(writeln!(w, "/* The menu art's top band, 240 x 64: per row, runs of one byte each (band colour << 4 | length - 1). */"))?;
    e(writeln!(w))?;
    e(writeln!(w, "#include <stdint.h>"))?;
    e(writeln!(w))?;
    e(writeln!(w, "/* UI palette index of each band colour. */"))?;
    let pal: Vec<String> = BAND.iter().map(|(_, i)| i.to_string()).collect();
    e(writeln!(w, "const uint8_t ui_art_top_pal[{}] = {{{}}};", BAND.len(), pal.join(", ")))?;
    e(writeln!(w))?;
    e(writeln!(w, "/* Where each row's runs start in ui_art_top. */"))?;
    e(writeln!(w, "const uint16_t ui_art_top_off[{H}] = {{"))?;
    for c in offs.chunks(16) {
        let v: Vec<String> = c.iter().map(|o| o.to_string()).collect();
        e(writeln!(w, "\t{},", v.join(", ")))?;
    }
    e(writeln!(w, "}};"))?;
    e(writeln!(w))?;
    e(writeln!(w, "const uint8_t ui_art_top[{}] = {{", data.len()))?;
    for c in data.chunks(16) {
        let v: Vec<String> = c.iter().map(|b| format!("0x{b:02x}")).collect();
        e(writeln!(w, "\t{},", v.join(", ")))?;
    }
    e(writeln!(w, "}};"))?;
    Ok(s)
}
